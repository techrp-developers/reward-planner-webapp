import sharp from 'sharp';
import { mkdir, writeFile, stat } from 'node:fs/promises';
const names = ['banner-itr-new', 'banner-pan-update', 'banner-car-new', 'banner-pan-service', 'banner-bike-new', 'banner-health-new', 'banner-car-offer'];
const directory = 'src/assets/servicescards/optimized';
await mkdir(directory, { recursive: true });
const imports = [], entries = [], report = [];
for (const [index, name] of names.entries()) {
  const input = `src/assets/servicescards/${name}.png`;
  const original = (await stat(input)).size;
  const formats = {};
  for (const format of ['webp', 'avif']) {
    formats[format] = [];
    for (const width of [320, 640, 1280]) {
      const filename = `${name}-${width}.${format}`;
      const path = `${directory}/${filename}`;
      let pipeline = sharp(input).resize({ width, withoutEnlargement: true });
      pipeline = format === 'webp' ? pipeline.webp({ quality: 84 }) : pipeline.avif({ quality: 62, effort: 4 });
      await pipeline.toFile(path);
      const outputWidth = (await sharp(path).metadata()).width;
      const variable = `image${index}_${format}_${width}`;
      imports.push(`import ${variable} from '../../assets/servicescards/optimized/${filename}';`);
      formats[format].push(`${variable} + ' ${outputWidth}w'`);
      report.push({ name, format, width: outputWidth, requestedWidth: width, originalBytes: original, bytes: (await stat(path)).size });
    }
  }
  entries.push(`[image${index}_webp_1280]: { webp: [${formats.webp.join(', ')}].join(', '), avif: [${formats.avif.join(', ')}].join(', ') }`);
}
await writeFile('src/components/services/serviceImageSources.ts', `// Generated by scripts/optimize-service-images.mjs. Keep original PNGs as source assets.\n${imports.join('\n')}\nexport const serviceImageSources: Record<string, {webp: string; avif: string}> = {\n${entries.join(',\n')}\n};\n`);
await mkdir('.services-validation', { recursive: true });
await writeFile('.services-validation/images.json', JSON.stringify(report, null, 2));
console.log('Generated responsive WebP/AVIF variants for seven existing banners.');
